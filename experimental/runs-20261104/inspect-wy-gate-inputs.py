#!/usr/bin/env python3
"""只读核对本轮 WY 门禁输入、冻结摘要和服务健康；不执行设备任务。"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import urllib.request


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def configuration(manifest):
    command = manifest['command']
    flags = ('--tensor-parallel-size', '--max-model-len', '--max-num-seqs',
             '--max-num-batched-tokens', '--compilation-config')
    return {flag: command[command.index(flag) + 1] for flag in flags} | {
        'image': manifest['image'],
        'prefix_caching': '--enable-prefix-caching' in command,
        'speculative_config_present': '--speculative-config' in command,
    }


def inspect(root, fixtures, service_manifest):
    replay_path = root / 'production-w8a8/replay-prompts.json'
    workload_path = fixtures / 'a1-310p-tune.workload.json'
    quality_path = root / 'production-w8a8/business-quality.jsonl'
    action_path = root / 'action-state-fixtures-v1.json'
    production_path = root / 'production-manifest.json'
    workload = json.loads(workload_path.read_text())
    calls = workload['recordings']['chinese_company_annual_meeting_planning']['calls']
    replay = json.loads(replay_path.read_text())
    keys = [f'chinese_company_annual_meeting_planning:0:{i}' for i in range(len(calls))]
    lengths = [len(replay[key]) for key in keys]
    assert lengths == [call['prompt_tokens'] for call in calls]
    quality = [json.loads(line) for line in quality_path.read_text().splitlines()]
    meeting_counts = [row['response']['usage']['prompt_tokens']
                      for row in quality if row['kind'] == 'meeting']
    actions = json.loads(action_path.read_text())['cases']
    with urllib.request.urlopen('http://127.0.0.1:18081/health') as response:
        health = response.status
    active = subprocess.check_output(
        ['systemctl', 'is-active', 'llm-backend-primary.service'], text=True).strip()
    containers = subprocess.check_output(
        ['podman', 'ps', '--format', '{{.Names}}'], text=True).splitlines()
    return {
        'date': '2026-11-04',
        'source_sha256': {
            'replay_prompts': sha(replay_path), 'workload': sha(workload_path),
            'business_quality': sha(quality_path), 'action_fixtures': sha(action_path),
            'production_manifest': sha(production_path),
            'live_service_manifest': sha(service_manifest),
        },
        'replay': {
            'calls': len(calls), 'prompt_tokens': lengths,
            'maximum_prompt_tokens': max(lengths),
            'input_tokens': sum(lengths),
            'output_tokens': sum(call['output_tokens'] for call in calls),
            'call_fields': sorted(calls[0]),
            'provenance': 'Real workload token shapes; synthetic text generated by replay_stage_workload.py; original text absent in workload',
        },
        'meeting_quality': {
            'cases': len(meeting_counts), 'minimum_prompt_tokens': min(meeting_counts),
            'maximum_prompt_tokens': max(meeting_counts),
        },
        'action_fixtures': [
            {'id': case['id'], 'tokens': case['token_info']['count'], 'scope': case['scope']}
            for case in actions
        ],
        'production_configuration': configuration(json.loads(production_path.read_text())),
        'live_service_configuration': configuration(json.loads(service_manifest.read_text())),
        'closeout': {
            'service_active_state': active, 'health_http_status': health,
            'running_rootless_containers': containers,
            'service_stopped_by_this_run': False,
            'restoration': 'not_required_service_unchanged',
        },
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--fixtures', type=Path, required=True)
    parser.add_argument('--service-manifest', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = inspect(args.root, args.fixtures, args.service_manifest)
    with args.out.open('x') as stream:
        json.dump(result, stream, ensure_ascii=False, indent=2)
        stream.write('\n')
    assert result['closeout']['health_http_status'] == 200
    assert result['closeout']['service_active_state'] == 'active'
    assert result['closeout']['running_rootless_containers'] == []


if __name__ == '__main__':
    main()
